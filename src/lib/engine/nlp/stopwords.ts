/**
 * Words that are stop words in ordinary prose but carry meaning on a resume, so they are
 * never filtered. "Lead" and "head" are job titles; "will" and "may" are also names.
 */
export const NEVER_STOP: ReadonlySet<string> = new Set(['c', 'r', 'go', 'it', 'ai', 'ui', 'ux']);

export function isStopWord(token: string): boolean {
	if (NEVER_STOP.has(token)) return false;
	return STOP_WORDS.has(token);
}
